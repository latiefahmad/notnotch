pub use ics::Event;

/// Fresh enough for a normal poll, and the least time between two forced refreshes.
const CACHE: Duration = Duration::from_secs(10 * 60);
const MIN_FORCED: Duration = Duration::from_secs(20);
const MAX_SOURCES: usize = 20;
const MAX_ICS_BYTES: usize = 20 * 1024 * 1024;
/// One source, all its requests included: a CalDAV account makes several, each with its own timeout, and the cache
/// stays locked while the sources are fetched.
const SOURCE_DEADLINE: Duration = Duration::from_secs(30);
// The month view goes back one month and ahead two: the window covers them whatever today is.
const DAYS_BACK: i64 = 62;
const DAYS_AHEAD: i64 = 100;
const CACHE_FILE: &str = "calendar-cache.json";

/// One source from the settings. `url` and `user` are only set for CalDAV (an ICS link is a secret).
#[derive(Deserialize, Clone)]
#[serde(rename_all = "camelCase")]
pub struct Source {
    id: String,
    kind: String,
    #[serde(default)]
    url: String,
    #[serde(default)]
    user: String,
    #[serde(default)]
    name: String,
    #[serde(default)]
    color: String,
}

#[derive(Clone, Serialize, Deserialize)]
#[serde(rename_all = "camelCase")]
pub struct CalendarInfo {
    id: String,
    source: String,
    name: String,
    /// `#rrggbb`, from the server or the source's colour.
    color: String,
}

/// A source's last good fetch; `key` changes with its address, user or secret, so an edited source never shows old data.
#[derive(Clone, Serialize, Deserialize)]
#[serde(rename_all = "camelCase")]
struct Entry {
    key: String,
    fetched_at: u64,
    calendars: Vec<CalendarInfo>,
    events: Vec<Event>,
}

#[derive(Clone, Serialize)]
#[serde(rename_all = "camelCase")]
pub struct SourceStatus {
    id: String,
    error: Option<String>,
    /// When its shown events were fetched (null: never).
    fetched_at: Option<u64>,
}

#[derive(Clone, Serialize)]
#[serde(rename_all = "camelCase")]
pub struct CalendarData {
    calendars: Vec<CalendarInfo>,
    events: Vec<Event>,
    sources: Vec<SourceStatus>,
    fetched_at: u64,
}

#[derive(Default)]
struct Cache {
    loaded: bool,
    entries: HashMap<String, Entry>,
    last: Option<(String, Instant, CalendarData)>,
}

/// Held across a fetch, so two calls never fetch the same sources at once.
#[derive(Default)]
pub struct CalendarState(tokio::sync::Mutex<Cache>);

/// The body as text, at most `max` bytes. Content-Length is missing on chunked replies, so the bytes are counted as
/// they arrive instead of buffering a huge reply first.
async fn read_capped(mut r: reqwest::Response, max: usize) -> Result<String, String> {
    if r.content_length().is_some_and(|n| n as usize > max) {
        return Err("too-large".into());
    }
    let mut body = Vec::new();
    while let Some(chunk) = r.chunk().await.map_err(net_error)? {
        if body.len() + chunk.len() > max {
            return Err("too-large".into());
        }
        body.extend_from_slice(&chunk);
    }
    Ok(String::from_utf8_lossy(&body).into_owned())
}

fn check_status(status: reqwest::StatusCode) -> Result<(), String> {
    match status.as_u16() {
        200..=299 => Ok(()),
        401 | 403 => Err("auth".into()),
        404 | 410 => Err("not-found".into()),
        _ => Err("failed".into()),
    }
}

/// Source ids are generated by the settings: short lowercase letters and digits (they also name the secret).
fn valid_id(id: &str) -> bool {
    !id.is_empty() && id.len() <= 24 && id.bytes().all(|b| b.is_ascii_lowercase() || b.is_ascii_digit())
}

/// `webcal://` and `webcals://` are https; only http and https are fetched.
fn web_url(raw: &str) -> Result<Url, String> {
    let raw = raw.trim();
    let lower = raw.to_ascii_lowercase();
    let fixed = if let Some(rest) = lower.strip_prefix("webcals://").or(lower.strip_prefix("webcal://")) {
        format!("https://{}", &raw[raw.len() - rest.len()..])
    } else if !raw.contains("://") {
        format!("https://{raw}")
    } else {
        raw.to_string()
    };
    let url = Url::parse(&fixed).map_err(|_| "bad-url".to_string())?;
    if !matches!(url.scheme(), "http" | "https") || url.host_str().is_none() {
        return Err("bad-url".into());
    }
    Ok(url)
}

fn hash<S: AsRef<str>>(parts: impl IntoIterator<Item = S>) -> String {
    let mut h = Sha256::new();
    for p in parts {
        h.update(p.as_ref().as_bytes());
        h.update([0]);
    }
    h.finalize().iter().take(8).map(|b| format!("{b:02x}")).collect()
}

/// The window in UTC: local midnight DAYS_BACK days ago to local midnight DAYS_AHEAD days ahead.
fn window(local: &TimeZone) -> (Timestamp, Timestamp) {
    let today = local.to_datetime(Timestamp::now()).date();
    let at = |days: i64| {
        recur::add_days(today, days)
            .and_then(|d| local.to_ambiguous_timestamp(d.to_datetime(jiff::civil::Time::midnight())).compatible().ok())
            .unwrap_or_else(Timestamp::now)
    };
    (at(-DAYS_BACK), at(DAYS_AHEAD))
}

fn cache_path(app: &AppHandle) -> Option<PathBuf> {
    crate::portable::app_data_dir(app).ok().map(|d| d.join(CACHE_FILE))
}

/// CalDAV follows redirects itself (caldav.rs), keeping PROPFIND and REPORT as they are.
fn client(follow_redirects: bool) -> Result<reqwest::Client, String> {
    let policy = if follow_redirects { reqwest::redirect::Policy::limited(5) } else { reqwest::redirect::Policy::none() };
    reqwest::Client::builder().timeout(Duration::from_secs(20)).user_agent("NotNotch").redirect(policy).build().map_err(|_| "failed".to_string())
}

/// Fetches one source; `key` is its fingerprint for the cache.
async fn fetch(src: &Source, secret: &str, key: &str, local: &TimeZone, (from, to): (Timestamp, Timestamp)) -> Result<Entry, String> {
    let own_color = ics::hex_color(&src.color).unwrap_or_default();
    let mut calendars = vec![];
    let mut events = vec![];
    let client = &client(src.kind == "ics")?;
    if src.kind == "ics" {
        let url = web_url(secret)?;
        let r = client.get(url.clone()).header("Accept", "text/calendar, */*").send().await.map_err(net_error)?;
        check_status(r.status())?;
        let text = read_capped(r, MAX_ICS_BYTES).await?;
        let (meta, list) = ics::events(&[&text], &src.id, from, to, local).ok_or("parse")?;
        let name = [src.name.trim(), meta.name.as_str(), url.host_str().unwrap_or("")].into_iter().find(|n| !n.is_empty()).unwrap_or("").to_string();
        let color = if own_color.is_empty() { meta.color } else { own_color };
        calendars.push(CalendarInfo { id: src.id.clone(), source: src.id.clone(), name, color });
        events = list;
    } else {
        let url = web_url(&src.url)?;
        let auth = caldav::Auth { user: src.user.trim(), pass: secret };
        let fmt = |t: Timestamp| t.strftime("%Y%m%dT%H%M%SZ").to_string();
        for cal in caldav::discover(client, &url, &auth).await? {
            let id = format!("{}/{}", src.id, hash([cal.href.as_str()]));
            let texts = caldav::events(client, &cal.href, &auth, &fmt(from), &fmt(to)).await?;
            let refs: Vec<&str> = texts.iter().map(|s| s.as_str()).collect();
            // An empty calendar returns no data at all, which is not a parse error.
            let list = if refs.is_empty() { vec![] } else { ics::events(&refs, &id, from, to, local).ok_or("parse")?.1 };
            calendars.push(CalendarInfo { id, source: src.id.clone(), name: cal.name, color: if cal.color.is_empty() { own_color.clone() } else { cal.color } });
            events.extend(list);
        }
    }
    Ok(Entry { key: key.to_string(), fetched_at: now_ms(), calendars, events })
}

/// Events of every source for the agenda. `force` skips the ten minutes' cache (but not the last 20 seconds').
#[tauri::command]
pub async fn calendar_fetch(app: AppHandle, sources: Vec<Source>, force: bool, state: State<'_, CalendarState>) -> Result<CalendarData, String> {
    if sources.len() > MAX_SOURCES || sources.iter().any(|s| !valid_id(&s.id) || (s.kind != "ics" && s.kind != "caldav")) {
        return Err("failed".into());
    }
    let mut cache = state.0.lock().await;
    let path = cache_path(&app);
    if !cache.loaded {
        cache.loaded = true;
        cache.entries = path.as_ref().and_then(|p| std::fs::read(p).ok()).and_then(|b| serde_json::from_slice(&b).ok()).unwrap_or_default();
    }
    // Each source with its secret (read here, never sent to the page) and fingerprint.
    let keyed: Vec<(Source, Option<String>, String)> = sources
        .into_iter()
        .map(|s| {
            let secret = crate::secrets::read(&format!("calendar.{}", s.id));
            let key = hash([s.kind.as_str(), s.url.trim(), s.user.trim(), secret.as_deref().unwrap_or("")]);
            (s, secret, key)
        })
        .collect();
    let sig = hash(keyed.iter().map(|(s, _, k)| format!("{}:{k}:{}:{}", s.id, s.name, s.color)));
    if let Some((last_sig, at, data)) = &cache.last {
        if *last_sig == sig && at.elapsed() < if force { MIN_FORCED } else { CACHE } {
            return Ok(data.clone());
        }
    }
    let local = TimeZone::system();
    let span = window(&local);
    let mut statuses = vec![];
    let mut entries: HashMap<String, Entry> = HashMap::new();
    for (src, secret, key) in &keyed {
        let cached = cache.entries.get(&src.id).filter(|e| e.key == *key).cloned();
        let result = match secret {
            None => Err("no-key".to_string()),
            Some(secret) => tokio::time::timeout(SOURCE_DEADLINE, fetch(src, secret, key, &local, span)).await.unwrap_or_else(|_| Err("offline".into())),
        };
        let (entry, error) = match result {
            Ok(e) => (Some(e), None),
            Err(e) => (cached, Some(e)),
        };
        statuses.push(SourceStatus { id: src.id.clone(), error, fetched_at: entry.as_ref().map(|e| e.fetched_at) });
        if let Some(mut e) = entry {
            // The name and colour typed in the settings apply to cached data too.
            if src.kind == "ics" {
                for c in &mut e.calendars {
                    if !src.name.trim().is_empty() {
                        c.name = src.name.trim().to_string();
                    }
                    if let Some(color) = ics::hex_color(&src.color) {
                        c.color = color;
                    }
                }
            }
            entries.insert(src.id.clone(), e);
        }
    }
    // Removed sources drop out of the file too.
    cache.entries = entries;
    if let Some(p) = &path {
        if cache.entries.is_empty() {
            let _ = std::fs::remove_file(p);
        } else if let Ok(json) = serde_json::to_vec(&cache.entries) {
            let _ = p.parent().map(std::fs::create_dir_all);
            let _ = std::fs::write(p, json);
        }
    }
    let from_ms = span.0.as_millisecond();
    let order: HashMap<&str, usize> = keyed.iter().enumerate().map(|(i, (s, _, _))| (s.id.as_str(), i)).collect();
    let mut list: Vec<&Entry> = cache.entries.values().collect();
    list.sort_by_key(|e| e.calendars.first().and_then(|c| order.get(c.source.as_str())).copied().unwrap_or(usize::MAX));
    let mut events: Vec<Event> = list.iter().flat_map(|e| e.events.iter().filter(|ev| ev.end > from_ms || ev.start >= from_ms).cloned()).collect();
    events.sort_by_key(|e| (e.start, e.end));
    let data = CalendarData { calendars: list.iter().flat_map(|e| e.calendars.clone()).collect(), events, sources: statuses, fetched_at: now_ms() };
    cache.last = Some((sig, Instant::now(), data.clone()));
    Ok(data)
}

/// An https link with a host and no user name, as parsed (and re-encoded) by Url.
fn https_link(raw: &str) -> Option<Url> {
    Url::parse(raw.trim()).ok().filter(|u| u.scheme() == "https" && u.host_str().is_some() && u.username().is_empty() && u.password().is_none())
}

/// Opens an event's meeting link in the default browser. Only https, so the page cannot start a program or open a file.
#[tauri::command]
pub fn calendar_open_link(url: String) -> Result<(), String> {
    let url = https_link(&url).ok_or("bad-url")?;
    crate::open_url(url.as_str())
}

#[cfg(test)]
mod tests {
    use super::*;

    #[test]
    fn only_https_links_open() {
        assert_eq!(https_link(" https://meet.google.com/abc-defg-hij ").unwrap().as_str(), "https://meet.google.com/abc-defg-hij");
        assert!(https_link("http://zoom.us/j/1").is_none());
        assert!(https_link("file:///C:/Windows/System32/cmd.exe").is_none());
        assert!(https_link("ms-settings:").is_none());
        assert!(https_link("https://user@zoom.us/j/1").is_none());
    }

    #[test]
    fn webcal_links_become_https() {
        assert_eq!(web_url("webcal://p52-caldav.icloud.com/published/2/AbC").unwrap().as_str(), "https://p52-caldav.icloud.com/published/2/AbC");
        assert_eq!(web_url("WEBCALS://x.example/a.ics").unwrap().as_str(), "https://x.example/a.ics");
        assert_eq!(web_url("calendar.google.com/calendar/ical/x/basic.ics").unwrap().host_str(), Some("calendar.google.com"));
        assert!(web_url("file:///C:/x.ics").is_err());
        assert!(web_url("javascript:alert(1)").is_err());
    }

    #[test]
    fn source_ids() {
        assert!(valid_id("k3x9a"));
        assert!(!valid_id(""));
        assert!(!valid_id("a.b"));
        assert!(!valid_id("A"));
        assert!(!valid_id(&"a".repeat(25)));
    }

    #[test]
    fn fingerprints_change_with_each_part() {
        assert_ne!(hash(["ics", "", "", "a"]), hash(["ics", "", "", "b"]));
        assert_ne!(hash(["ab", "c"]), hash(["a", "bc"]));
        assert_eq!(hash(["x"]).len(), 16);
    }
}
